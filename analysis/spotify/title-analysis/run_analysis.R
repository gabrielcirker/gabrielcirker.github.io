source("config.R", local=TRUE)
source("R/functions.R", local=TRUE)
check_dependencies()
set.seed(config$seed)
input <- Sys.getenv("SPOTIFY_INPUT", unset=config$input)
config$output <- "outputs"
dir.create(config$output,showWarnings=FALSE,recursive=TRUE)
raw <- read_history(input)
analysis <- analyze_history(raw,config)
write_result <- function(x,name) readr::write_csv(x,file.path(config$output,paste0(name,".csv")),na="NA")
for(n in c("audit","primary","salience","diversity","edges")) write_result(analysis[[n]],c(audit="quality_summary",primary="word_comparison",salience="lexical_salience",diversity="monthly_diversity",edges="word_cooccurrence")[[n]])
write_result(analysis$drift$comparisons,"monthly_jsd")
write_result(analysis$drift$vocabulary,"fixed_vocabulary")
write_result(analysis$drift$word_mass,"monthly_word_mass")
for(n in c("counts","examples","salience","comparison"))write_result(analysis$annotation[[n]],paste0("annotation_",n))
write_result(data.frame(file=basename(input),algorithm="MD5",digest=unname(tools::md5sum(input))),"input_hash")
writeLines(capture.output(dput(config)),"outputs/analysis_config.R")
writeLines(capture.output(sessionInfo()),"outputs/sessionInfo.txt")
plots <- list(word_weighting=plot_presence(analysis$primary),lexical_salience=plot_salience(analysis$salience),monthly_diversity=plot_diversity(analysis$diversity),vocabulary_drift=plot_drift(analysis$drift$comparisons))
source("tests/self_checks.R",local=TRUE)
